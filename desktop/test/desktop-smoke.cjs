// Run with Electron, not node --test. Uses an isolated temporary profile and
// never makes an API request. Linux CI may require an isolated display server.
const { app, BrowserWindow } = require('electron');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const assert = require('node:assert/strict');
const profile = fs.mkdtempSync(path.join(os.tmpdir(), 'roody-ui-test-'));
app.setPath('userData', profile);
delete process.env.OPENAI_API_KEY;
require('../main');
const timeout = setTimeout(() => { console.error('UI smoke test timed out'); app.exit(1); }, 30000);
app.whenReady().then(async () => {
  const win = BrowserWindow.getAllWindows()[0];
  if (win.webContents.isLoading()) await new Promise(resolve => win.webContents.once('did-finish-load', resolve));
  const errors = [];
  win.webContents.on('console-message', (_event, details) => { if (details.level === 'error') errors.push(details.message); });
  const result = await win.webContents.executeJavaScript(`(async () => {
    for (let i=0;i<100 && !document.getElementById('notice').textContent.includes('API key missing');i++) await new Promise(r=>setTimeout(r,20));
    await window.roody.expand(true);
    document.getElementById('panel').hidden = false;
    const settingsOpenedWithoutKey = !document.getElementById('settings').hidden;
    document.getElementById('api-key').value = 'sk-ui-test-not-a-real-credential';
    document.getElementById('remember-key').checked = false;
    await document.getElementById('key-form').onsubmit({preventDefault(){}});
    const saved = await window.roody.state();
    const fieldCleared = document.getElementById('api-key').value === '';
    const metadataLeaksKey = JSON.stringify(saved).includes('sk-ui-test-not-a-real-credential');
    const savedStatus = document.getElementById('key-status').textContent;
    await document.getElementById('remove-key').onclick();
    const removed = await window.roody.state();
    const set = await window.roody.memory({type:'goal',text:'Get login working before the demo'});
    const taskState = await window.roody.memory({type:'add-task',text:'Inspect the 401 response'});
    renderMemory(taskState);
    document.getElementById('persona').value='grandparent';
    await document.getElementById('persona').onchange();
    await document.getElementById('demo').onclick();
    const demo = document.getElementById('text').value;
    openSettings(true);
    return {settingsOpenedWithoutKey,hasKeyAfterSave:saved.hasKey,fieldCleared,metadataLeaksKey,savedStatus,hasKeyAfterRemove:removed.hasKey,goal:set.goal,tasks:taskState.tasks.length,demo,persona:document.getElementById('persona').value,bridge:typeof window.roody.ask,nodeAccess:typeof require};
  })()`);
  assert.equal(result.settingsOpenedWithoutKey, true);
  assert.equal(result.hasKeyAfterSave, true);
  assert.equal(result.fieldCleared, true);
  assert.equal(result.metadataLeaksKey, false);
  assert.match(result.savedStatus, /this session/);
  assert.equal(result.hasKeyAfterRemove, false);
  assert.equal(fs.existsSync(path.join(profile, 'openai-key.enc')), false);
  assert.equal(result.goal, 'Get login working before the demo');
  assert.equal(result.tasks, 1);
  assert.equal(result.persona, 'grandparent');
  assert.match(result.demo, /DEMO SAMPLE/);
  assert.equal(result.bridge, 'function');
  assert.equal(result.nodeAccess, 'undefined');
  assert.equal(JSON.parse(fs.readFileSync(path.join(profile, 'memory.json'), 'utf8')).tasks.length, 1);
  assert.deepEqual(errors, []);
  const image = await win.webContents.capturePage();
  const screenshot = path.join(os.tmpdir(), 'roody-desktop-smoke.png');
  fs.writeFileSync(screenshot, image.toPNG());
  console.log('PASS desktop loads; settings key save/removal; no key in metadata; goal/task persistence; grandparent demo selection; renderer has no Node access');
  console.log('Screenshot: ' + screenshot);
  clearTimeout(timeout); app.quit();
}).catch(error => { clearTimeout(timeout); console.error(error); app.exit(1); });
